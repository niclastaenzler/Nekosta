-- Zusätzliche Schemaelemente, damit der Export-/Import-Test alles abdeckt
create type abr_status as enum ('entwurf', 'abgeschlossen');
create table user_profiles (user_id uuid primary key references auth.users(id) on delete cascade, full_name text, nekosta_theme text, nr bigint generated by default as identity, status abr_status default 'entwurf', constraint name_len check (char_length(full_name) < 200));
alter table user_profiles enable row level security;
create policy prof_own on user_profiles for all to authenticated using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));
create index if not exists kontakte_nachname_idx on kontakte (lower(nachname));
create or replace function public.handle_new_user() returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.user_profiles(user_id, full_name) values (new.id, new.raw_user_meta_data->>'full_name') on conflict do nothing;
  return new;
end $$;
create trigger on_auth_user_created after insert on auth.users for each row execute function public.handle_new_user();
create or replace function public.touch_updated() returns trigger language plpgsql as $$ begin new.firma = coalesce(new.firma, ''); return new; end $$;
create trigger stammdaten_touch before insert or update on stammdaten for each row execute function public.touch_updated();
create view objekt_uebersicht as select o.id, o.user_id, o.name, (select count(*) from einheiten e where e.objekt_id = o.id) as einheiten from objekte o;

-- NEKOSTA: komplettes Datenbankschema als SQL-Text exportieren.
-- Im Supabase-Dashboard unter „SQL Editor" ausführen; das Ergebnis (eine Zelle „ddl")
-- als Datei schema.sql speichern. Enthält KEINE Daten, nur die Struktur.
with
pub as (select oid from pg_namespace where nspname = 'public'),
tbls as (
  select c.oid, c.relname from pg_class c where c.relnamespace = (select oid from pub) and c.relkind in ('r','p')
    and c.relname not like '\_nekosta%' and not exists (select 1 from pg_depend d where d.objid = c.oid and d.deptype = 'e')
),
enums as (
  select 1 as ord, t.typname as k, format('create type public.%I as enum (%s);', t.typname,
    (select string_agg(quote_literal(e.enumlabel), ', ' order by e.enumsortorder) from pg_enum e where e.enumtypid = t.oid)) as stmt
  from pg_type t where t.typnamespace = (select oid from pub) and t.typtype = 'e'
),
seqs as (
  select 2, c.relname, format('create sequence if not exists public.%I;', c.relname)
  from pg_class c where c.relnamespace = (select oid from pub) and c.relkind = 'S'
    and not exists (select 1 from pg_depend d where d.objid = c.oid and d.deptype in ('a','i'))
),
tabs as (
  select 3, t.relname, format('create table public.%I (%s);', t.relname, (
    select string_agg(format('%I %s%s%s%s', a.attname, format_type(a.atttypid, a.atttypmod),
      case when a.attidentity = 'a' then ' generated always as identity' when a.attidentity = 'd' then ' generated by default as identity' else '' end,
      case when a.attgenerated = 's' then ' generated always as (' || pg_get_expr(ad.adbin, ad.adrelid) || ') stored'
           when ad.adbin is not null and a.attidentity = '' then ' default ' || pg_get_expr(ad.adbin, ad.adrelid) else '' end,
      case when a.attnotnull then ' not null' else '' end), ', ' order by a.attnum)
    from pg_attribute a left join pg_attrdef ad on ad.adrelid = a.attrelid and ad.adnum = a.attnum
    where a.attrelid = t.oid and a.attnum > 0 and not a.attisdropped))
  from tbls t
),
funcs as (
  select 4, p.proname || '(' || pg_get_function_identity_arguments(p.oid) || ')', pg_get_functiondef(p.oid) || ';'
  from pg_proc p where p.pronamespace = (select oid from pub) and p.prokind in ('f','p')
    and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
),
views as (
  select 5, c.relname, format('create or replace view public.%I as %s', c.relname, pg_get_viewdef(c.oid))
  from pg_class c where c.relnamespace = (select oid from pub) and c.relkind = 'v'
),
cons as (
  select case when con.contype = 'f' then 7 else 6 end, t.relname || '.' || con.conname,
    format('alter table public.%I add constraint %I %s;', t.relname, con.conname, pg_get_constraintdef(con.oid))
  from pg_constraint con join tbls t on t.oid = con.conrelid where con.contype in ('p','u','c','f','x')
),
idx as (
  select 8, i.relname, pg_get_indexdef(i.oid) || ';'
  from pg_index x join pg_class i on i.oid = x.indexrelid join tbls t on t.oid = x.indrelid
  where not exists (select 1 from pg_constraint con where con.conindid = x.indexrelid)
),
trg as (
  select 9, n.nspname || '.' || c.relname || '.' || tg.tgname, pg_get_triggerdef(tg.oid) || ';'
  from pg_trigger tg join pg_class c on c.oid = tg.tgrelid join pg_namespace n on n.oid = c.relnamespace
  join pg_proc p on p.oid = tg.tgfoid
  where not tg.tgisinternal and (n.nspname = 'public' or (n.nspname in ('auth','storage') and p.pronamespace = (select oid from pub)))
),
rls as (
  select 10, t.relname, format('alter table public.%I enable row level security;', t.relname)
  from tbls t join pg_class c on c.oid = t.oid where c.relrowsecurity
),
pol as (
  select 11, p.schemaname || '.' || p.tablename || '.' || p.policyname,
    format('create policy %I on %I.%I as %s for %s to %s%s%s;', p.policyname, p.schemaname, p.tablename, p.permissive, p.cmd,
      (select string_agg(case when r = 'public' then 'public' else quote_ident(r) end, ', ') from unnest(p.roles) r),
      case when p.qual is not null then ' using (' || p.qual || ')' else '' end,
      case when p.with_check is not null then ' with check (' || p.with_check || ')' else '' end)
  from pg_policies p where p.schemaname = 'public' or (p.schemaname = 'storage' and p.tablename = 'objects')
),
buckets as (
  select 12, b.id, format('insert into storage.buckets (id, name, public) values (%L, %L, %L) on conflict (id) do nothing;', b.id, b.name, b.public)
  from storage.buckets b
),
alls as (
  select * from enums union all select * from seqs union all select * from tabs union all select * from funcs union all
  select * from views union all select * from cons union all select * from idx union all select * from trg union all
  select * from rls union all select * from pol union all select * from buckets
)
select '-- NEKOSTA Schema-Export ' || now()::text || E'\nset check_function_bodies = off;\n\n'
  || string_agg(stmt, E'\n\n' order by ord, k) || E'\n' as ddl
from alls;
